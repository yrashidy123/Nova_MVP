"""Bundle the team's synthetic dataset into nova-data.js for index.html.

Reads nova-assist/data/*.csv and nova-assist/data/evals/eval_cases.json and
writes nova-data.js at the repo root. Run it again whenever the data changes:

    python scripts/build_data.py

Fields the customer-facing copilot must never see are dropped here, so they
never reach the browser: tickets.agent_notes, disputes.internal_note, and
customers' email, phone and employer.
"""
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "nova-assist" / "data"
OUT = ROOT / "nova-data.js"

DROP = {
    "customers": {"email", "phone", "employer"},
    "tickets": {"agent_notes"},
    "disputes": {"internal_note"},
}
NUMERIC = {
    "customers": {"tenure_months", "avg_monthly_balance_egp", "overdraft_limit_egp"},
    "transactions": {"amount_egp", "amount_original"},
    "disputes": {"amount_egp", "provisional_credit_egp"},
}


def read(name):
    rows = []
    with open(DATA / f"{name}.csv", encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            for k in DROP.get(name, ()):
                row.pop(k, None)
            for k in NUMERIC.get(name, ()):
                row[k] = float(row[k]) if row.get(k) else None
            rows.append(row)
    return rows


def sections(body):
    """Split a policy body into its numbered '## §n Title' sections."""
    out = []
    for m in re.finditer(r"^## §(\d+) (.+?)\n(.*?)(?=^## §|\Z)", body, re.S | re.M):
        out.append({"num": int(m.group(1)), "title": m.group(2).strip(), "text": m.group(3).strip()})
    return out


def main():
    policies = []
    for p in read("policies"):
        secs = sections(p["body"])
        policies.append({
            "id": p["policy_id"], "title": p["title"], "category": p["category"],
            "effective": p["effective_date"],
            "sections": [{"id": f'{p["policy_id"]} §{s["num"]}', **s} for s in secs],
        })
    evals = json.loads((DATA / "evals" / "eval_cases.json").read_text(encoding="utf-8"))
    data = {
        "asOf": evals.get("as_of", "2026-09-18"),
        "dataset": evals.get("dataset", ""),
        "customers": read("customers"),
        "transactions": read("transactions"),
        "cards": read("cards"),
        "disputes": read("disputes"),
        "tickets": read("tickets"),
        "policies": policies,
    }
    js = (
        "// Generated by scripts/build_data.py from nova-assist/data. Do not edit by hand.\n"
        f"window.NOVA_DATA={json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n"
        f"window.NOVA_EVALS={json.dumps(evals['cases'], ensure_ascii=False, separators=(',', ':'))};\n"
    )
    OUT.write_text(js, encoding="utf-8")
    n_secs = sum(len(p["sections"]) for p in policies)
    print(f"Wrote {OUT.name}: {len(data['customers'])} customers, {len(data['transactions'])} transactions, "
          f"{len(data['cards'])} cards, {len(data['disputes'])} disputes, {len(data['tickets'])} tickets, "
          f"{len(policies)} policies ({n_secs} sections), {len(evals['cases'])} eval cases, {OUT.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
